"""The startup art, mirrored into the Rust client.

`novacode_cli/brand.py` owns the art; this script emits it as Rust constants so
the client draws the same characters without duplicating them by hand. Run it
after any change to the art, and `--check` in CI to catch drift:

    uv run python scripts/gen_brand_art.py
    uv run python scripts/gen_brand_art.py --check
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from novacode_cli import brand  # noqa: E402

OUT = ROOT / "rust" / "nova-tui" / "src" / "ui" / "brand_art.rs"

HEADER = '''//! Generated by `scripts/gen_brand_art.py` from `novacode_cli/brand.py`.
//!
//! Do not edit by hand: change the Python art and regenerate.

'''


def _rows(name: str, lines: tuple[str, ...]) -> str:
    body = "\n".join(f'    "{line}",' for line in lines)
    return f"/// `brand.{name}`, one entry per row.\npub const {name.upper()}: &[&str] = &[\n{body}\n];\n"


def render() -> str:
    """The whole generated module."""
    portrait = brand.portrait()
    parts = [
        HEADER,
        "/// Cells the portrait occupies, after right-padding.\n"
        f"pub const PORTRAIT_WIDTH: u16 = {brand.PORTRAIT_WIDTH};\n",
        _rows("portrait", portrait),
        "/// Cells the wordmark occupies; uniform by construction.\n"
        f"pub const WORDMARK_WIDTH: u16 = {brand.WORDMARK_WIDTH};\n",
        _rows("WORDMARK_LINES", brand.WORDMARK_LINES),
        "/// Cells between the portrait and the caption column.\n"
        f"pub const COLUMN_GAP: u16 = {brand._GAP};\n",  # noqa: SLF001 - the geometry is the art
        "/// Cells the caption column occupies.\n"
        f"pub const COLUMN_WIDTH: u16 = {brand._COLUMN_WIDTH};\n",  # noqa: SLF001
        "/// Cells the transcript insets the banner by, each side.\n"
        f"pub const TRANSCRIPT_INSET: u16 = {brand._TRANSCRIPT_INSET};\n",  # noqa: SLF001
        "/// Rows below which the banner drops to the wordmark alone.\n"
        f"pub const TALL_MIN_HEIGHT: u16 = {brand.TALL_MIN_HEIGHT};\n",
        "/// The single-line mark for terminals too narrow for any art.\n"
        f'pub const COMPACT_MARK: &str = "{brand.compact_mark()}";\n',
        "/// The line under the portrait when only it fits.\n"
        f'pub const NAME_LINE: &str = "{brand._NAME_LINE}";\n',  # noqa: SLF001
    ]
    return "\n".join(parts)


def main() -> int:
    """Write the module, or verify it is current."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the file is stale")
    args = parser.parse_args()
    wanted = render()
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != wanted:
            print(f"{OUT.relative_to(ROOT)} is stale: run scripts/gen_brand_art.py", file=sys.stderr)
            return 1
        print("brand art ok")
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(wanted, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
